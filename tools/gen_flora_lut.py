#!/usr/bin/env python3
"""Generate firmware/src/flora/flora_lut.h: a quarter-wave sine table (Q14) for the flora engine.

The engine works in integer maths only (the FM-1's AC79 has no FPU in use), so the table is generated
here once instead of at boot.
"""
import math
import pathlib

N = 256  # quarter wave -> 1024 steps per full turn
vals = [round(math.sin(i * math.pi / 2 / N) * 16384) for i in range(N + 1)]
out = pathlib.Path(__file__).resolve().parent.parent / "firmware" / "src" / "flora" / "flora_lut.h"
lines = ["/* Generated by tools/gen_flora_lut.py - do not edit. */",
         "#ifndef FLORA_LUT_H", "#define FLORA_LUT_H", "#include <stdint.h>",
         "/* sin(i * pi/2 / 256) in Q14, i = 0..256 */",
         "static const int16_t fl_qsin[257] = {"]
for i in range(0, N + 1, 12):
    lines.append("    " + ", ".join(str(v) for v in vals[i:i + 12]) + ",")
lines += ["};", "#endif", ""]
out.write_text("\n".join(lines))
print("wrote", out)
