"""The polyphase FIR of ChoralRoot In's 44.1 -> 48 kHz resampler (firmware/src/usb_audio_stream.c, ua_resample).
SLOOP 2.5's tools/gen_uac_fir.py (after Felucca 1.1.5's, Leo Kuroshita: 24 taps a phase in Q30; SLOOP made it 12
taps in Q15), unchanged in its numbers: the table it writes is SLOOP 2.5's firmware/src/uac_fir.h value for value.

48000 / 44100 = 160 / 147: up by L = 160, low-pass, down by M = 147. Output frame k sits at input time
k * 147 / 160: phase p = (k * 147) % 160, newest input frame floor(k * 147 / 160). Each phase is N taps of
the prototype (a Kaiser-windowed sinc of 160 * N taps at 7.056 MHz, cut-off FC):
    y[k] = sum_j  PROTO[p + 160 j] * x[base - j],   j = 0 .. N-1
The table holds the taps oldest input first, Q15, and only the phases 0 .. 79: the prototype is symmetric,
so phase 159 - p is phase p read backwards. Each phase's taps sum to exactly 1 << 15 (unity gain at DC).
Why these numbers (tests/cr_usbaudio48_test.c measures them on the C code): N = 12, FC = 20 kHz, beta 7.5: images
that would fold into the audible band are down about 80 dB, the passband is flat to about 12 kHz (-1 dB at 16 kHz,
-2.7 dB at 18 kHz), the 1 kHz SNR is above 80 dB. Six channels are filtered on the unit, so the taps are the cost:
docs/USB-AUDIO.md "48 kHz".
  tools/gen_uac_fir.py [OUT]      (default firmware/src/uac_fir.h); numpy only
  tools/gen_uac_fir.py --report [N [FC [BETA]]]   the prototype's figures for a filter of N taps a phase (no file)"""
import sys
from pathlib import Path

import numpy as np

L, M, N = 160, 147, 12
FC, BETA, QB = 20000.0, 7.5, 15
FS = 44100.0


def prototype(n_taps=N, fc_hz=FC, beta=BETA):
    n = L * n_taps
    t = np.arange(n) - (n - 1) / 2.0
    fc = fc_hz / (FS * L)
    h = 2 * fc * np.sinc(2 * fc * t) * np.kaiser(n, beta)
    return h / h.sum() * L


def table(n_taps=N, fc_hz=FC, beta=BETA):
    h = prototype(n_taps, fc_hz, beta)
    tab = np.zeros((L, n_taps), dtype=np.int64)
    for p in range(L):
        c = h[p::L][::-1]
        q = np.round(c * (1 << QB)).astype(np.int64)
        q[np.argmax(np.abs(c))] += (1 << QB) - q.sum()
        tab[p] = q
    for p in range(L // 2):
        assert np.abs(tab[L - 1 - p] - tab[p][::-1]).max() <= 1
    assert np.abs(tab).max() < 32768 and np.abs(tab).sum(axis=1).max() < 2 * 32768   # (int32 sums in C)
    return tab


def report(n_taps, fc_hz, beta):
    """the quantised prototype's response (the table's taps put back at 7.056 MHz): the passband, and what an input
    tone at f leaves at its first image 44100 - f, which lands at 48000 - (44100 - f) = f + 3900 Hz in the output"""
    tab = table(n_taps, fc_hz, beta)
    h = np.zeros(L * n_taps)
    for p in range(L):
        h[p::L] = tab[p][::-1] / float(1 << QB)

    def db(f):
        w = 2 * np.pi * f / (FS * L)
        return 20 * np.log10(abs(np.sum(h * np.exp(-1j * w * np.arange(len(h))))) / L + 1e-12)
    print(f"N {n_taps} taps a phase, cut-off {fc_hz:g} Hz, Kaiser beta {beta:g}, Q{QB}: table {L // 2 * n_taps * 2} B")
    print("  passband: " + ", ".join(f"{f / 1000:g} kHz {db(f):+.2f} dB" for f in (1000, 5000, 10000, 12000, 14000,
                                                                                    16000, 18000, 20000)))
    print("  first image of an input tone (at 44100 - f, heard at f + 3900 Hz in the 48 kHz output), below the tone:")
    for f in (1000, 5000, 10000, 12000, 14000, 16000, 18000, 20000):
        print(f"    {f / 1000:g} kHz -> {(f + 3900) / 1000:g} kHz: {db(FS - f) - db(f):+.1f} dB")
    worst = max(db(f) for f in np.arange(FS - 16100.0, 3 * FS, 50.0))
    print(f"  stopband from 28 kHz (the images that land under 20 kHz): {worst:+.1f} dB at most")


def main():
    if len(sys.argv) > 1 and sys.argv[1] == "--report":
        a = sys.argv[2:]
        report(int(a[0]) if a else N, float(a[1]) if len(a) > 1 else FC, float(a[2]) if len(a) > 2 else BETA)
        return
    out = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / "firmware" / "src" / "uac_fir.h")
    tab = table()
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-only */",
        "/* generated by tools/gen_uac_fir.py: do not edit. The 44.1 -> 48 kHz polyphase FIR of the USB audio input",
        f" * (usb_audio_stream.c ua_resample): L {L}, M {M}, {N} taps per phase, Kaiser beta {BETA:g}, cut-off {FC:g} Hz, Q{QB}; phases 0..{L // 2 - 1}",
        f" * (phase {L - 1} - p = phase p backwards), taps oldest input first. SLOOP 2.5's table, value for value (its",
        " * firmware/src/uac_fir.h), after Felucca 1.1.5 (24 taps, Q30). */",
        f"#define UAC_FIR_L {L}u",
        f"#define UAC_FIR_M {M}u",
        f"#define UAC_FIR_N {N}u",
        f"#define UAC_FIR_Q {QB}",
        f"static const int16_t UAC_FIR[{L // 2}][{N}] = {{",
    ]
    for p in range(L // 2):
        lines.append("    {" + ", ".join(str(int(v)) for v in tab[p]) + "},")
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}: {L // 2} x {N} taps, {L // 2 * N * 2} B")


if __name__ == "__main__":
    main()
