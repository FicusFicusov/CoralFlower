"""Sampled drum kits for the sequencer's drums (firmware/src/drum_smp.c): assets/drum-kits/<KIT>/<sound>.wav ->
firmware/src/drum_smp_data.h (IMA ADPCM, 4 bit, as eng_sample.c's; each sound at its own rate).

  python3 tools/gen_drum_samples.py            (needs ffmpeg and numpy; run by hand, the header is kept in the tree)

A kit: bd sd cp hh oh mt rim bell cr (drum_synth.c's DSS_* order). Each is cut to its cap, faded out, set to its
level and stored from the first sample above -40 dB.
"""
import subprocess
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sampleio import ima_encode  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "assets" / "drum-kits"
OUT = ROOT / "firmware" / "src" / "drum_smp_data.h"
# kits: folder, the name shown (7 letters at most), its gain (Q12, set by tools' host render to the X kits' loudness)
KITS = [("S808", 3500), ("S909", 4096), ("SLINN", 4800)]
# sound: file, rate, cap (s), level (of full scale)
SOUNDS = [("bd", 22050, 0.90, 0.95), ("sd", 32000, 0.45, 0.85), ("cp", 32000, 0.50, 0.80), ("hh", 32000, 0.20, 0.55),
          ("oh", 32000, 0.60, 0.55), ("mt", 22050, 0.60, 0.85), ("rim", 32000, 0.20, 0.70), ("bell", 32000, 0.60, 0.60),
          ("cr", 32000, 1.20, 0.60)]


def load(path, rate):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(path), "-ac", "1", "-ar", str(rate), "-f", "s16le", "-"],
                         check=True, capture_output=True).stdout
    return np.frombuffer(raw, "<i2").astype(np.float64) / 32768.0


def main():
    data, zones, report = bytearray(), [], []
    for kit, _ in KITS:
        for name, rate, cap, level in SOUNDS:
            x = load(SRC / kit / f"{name}.wav", rate)
            a = np.abs(x)
            start = int(np.argmax(a > 0.01 * a.max()))
            x = x[max(0, start - 2):][: int(cap * rate)]
            a = np.abs(x)
            last = len(x) - int(np.argmax(a[::-1] > 0.003 * a.max()))      # (the tail below -50 dB: not stored)
            x = x[: max(last, 64)]
            nf = min(len(x) // 3, int(0.03 * rate))
            x[-nf:] *= np.linspace(1.0, 0.0, nf) ** 2
            x = x / np.abs(x).max() * level
            pcm = [int(v) for v in np.clip(np.round(x * 32767), -32768, 32767)]
            enc, _ = ima_encode(pcm, 0)
            zones.append((len(data), len(pcm), round(rate * 65536 / 44100)))
            report.append(f"{kit:6s} {name:4s} {len(pcm) / rate:5.2f} s  {len(enc):6d} B")
            data += enc
    L = ["/* generated by tools/gen_drum_samples.py from assets/drum-kits (README.md there) */",
         f"#define DSM_NKIT {len(KITS)}u", f"#define DSM_NSND {len(SOUNDS)}u",
         "typedef struct { uint32_t off, n, rate; } dsm_zone_t;   /* bytes into DSM_DATA, samples, rate / 44100 (Q16) */",
         "static const uint16_t DSM_GAIN[DSM_NKIT] = {" + ", ".join(str(g) for _, g in KITS) + "};   /* Q12 */",
         "static const dsm_zone_t DSM_ZONE[DSM_NKIT * DSM_NSND] = {"]
    for i, (off, n, r) in enumerate(zones):
        L.append(f"    {{{off}, {n}, {r}}},   /* {KITS[i // len(SOUNDS)][0]} {SOUNDS[i % len(SOUNDS)][0]} */")
    L += ["};", f"static const uint8_t DSM_DATA[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        L.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    L.append("};")
    OUT.write_text("\n".join(L) + "\n")
    print("\n".join(report))
    print(f"{OUT}: {len(data)} B of samples")


if __name__ == "__main__":
    main()
